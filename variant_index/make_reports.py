#!/usr/bin/env python3
"""Coverage statistics, validation, target lifecycle, change log and gap report for a built index.

    python3 variant_index/make_reports.py [--index data/index] [--out data/index/reports] [--previous OLD_INDEX] [--markdown variant_index/BUILD_REPORT.md] [--skip-validation]

Writes coverage.json, validation.json, lifecycle.json, gaps.json (and change_log.json when --previous is given) under --out and, with --markdown, a readable summary
that is safe to commit (counts and statuses only; it holds no personal data). Every number is recomputed from the index and the acquisition records on each run.
"""
import argparse
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from vindex import reports                                         # noqa: E402
from vindex.build.common import DATA, OUT_DEFAULT                  # noqa: E402
from vindex.refgenome import Reference                             # noqa: E402

FASTA = os.path.join(DATA, 'reference_sequence', 'Homo_sapiens.GRCh38.dna.toplevel.fa.gz')
REPORT = os.path.join(DATA, 'refseq', 'GCF_000001405.40_GRCh38.p14_assembly_report.txt')


def md(cov, val, life, gaps, change, manifest):
    L = ['# Build report', '', f"Index schema {manifest.get('schema_version')}, built {manifest.get('built_utc')}. Generated by `variant_index/make_reports.py`; regenerate it after any rebuild.", '']
    t = cov['tables']
    L += ['## Table sizes', '', '| Table | Files | Rows |', '|---|---:|---:|'] + [f"| {k} | {v['files']} | {v['rows']:,} |" for k, v in t.items()] + ['']
    ev = cov.get('evidence') or {}
    if ev:
        L += ['## Evidence rows', '', f"Total {ev['total']:,}.", '', '| Source | Rows |', '|---|---:|'] + [f'| {k} | {v:,} |' for k, v in ev['source_id'].items()] + ['']
        L += ['| Axis | Rows | Distinct variants with mapped evidence |', '|---|---:|---:|'] + [f"| {k} | {v:,} | {ev.get('variants_with_evidence_by_axis', {}).get(k, 0):,} |" for k, v in ev['axis'].items()] + ['']
        L += ['| Mapping status | Rows |', '|---|---:|'] + [f'| {k} | {v:,} |' for k, v in ev['mapping_status'].items()] + ['']
        L += ['Retained but not mapped (largest reasons):', '', '| Source | Status | Reason | Rows |', '|---|---|---|---:|'] + [f"| {k.split('|')[0]} | {k.split('|')[1]} | {k.split('|')[2]} | {v:,} |" for k, v in list(ev['not_mapped'].items())[:25]] + ['']
    lin = cov.get('lineage')
    if lin:
        L += ['## Shared lineage', '', f"{lin['groups']:,} lineage groups; {lin['shared_between_sources']:,} are written by more than one source. Rows of one group descend from one study or record and count once in the independence tally.", '',
              '| Sources | Groups both write |', '|---|---:|'] + [f"| {k.replace('|', ' and ')} | {v:,} |" for k, v in list(lin['source_pairs'].items())[:25]] + ['']
    xc = cov.get('xref_coherence')
    if xc:
        L += ['## dbSNP identifiers placed at more than one site', '', f"{xc['identifiers']:,} dbSNP identifiers are cross-referenced to variants; {xc['multi_position']:,} resolve to more than one position "
              f"({xc['multi_position_across_sources']:,} placed differently by different sources, {xc['multi_position_within_one_source']:,} within one source). Sources reach an rsID by different routes, "
              "so a disagreement is a mapping error, a merged identifier or a locus that exists twice (the pseudoautosomal regions); it is counted here, not judged.", '']
        if xc['source_pairs']:
            L += ['| Sources that place an identifier differently | Identifiers |', '|---|---:|'] + [f"| {k.replace('|', ' and ')} | {v:,} |" for k, v in list(xc['source_pairs'].items())[:25]] + ['']
        if xc['examples']:
            L += ['Examples: ' + '; '.join(f"`{e['identifier']}` " + ', '.join(f'{r} at {l}' for r, l in e['placed'].items()) for e in xc['examples'][:5]), '']
    if val:
        L += ['## Validation', '', f"**{'passed' if val['ok'] else 'FAILED'}**; {val.get('evidence_rows_checked', 0):,} evidence rows checked, {val.get('entity_variant_ref_checked', 0):,} variant REF alleles read back from the reference.", '',
              '| Check | Violations |', '|---|---:|'] + [f"| {k} | {c['violations']} |" for k, c in val['checks'].items()] + ['']
        if val.get('informational'):
            L += ['Counted but not failing the validation (a source names a gene that the gene table does not hold: the row is kept, the gene has no symbol):', '', '| Count | Rows |', '|---|---:|'] + \
                 [f'| {k} | {v:,} |' for k, v in val['informational'].items()] + ['']
    s = life['summary']
    L += ['## Target lifecycle', '', f"{s['total']} targets: listed {s['listed']}, acquired {s['acquired']}, verified {s['verified']}, mapped {s['mapped']}, integrated {s['integrated']}.", '']
    L += ['Acquired but not integrated:', ''] + [f'- `{t}`' for t in life['acquired_not_integrated']] + ['']
    L += ['Listed but not acquired (data not in this environment):', ''] + [f'- `{t}`' for t in gaps['targets_not_acquired']] + ['']
    L += ['Acquired but not verified by an acquisition validator:', ''] + ([f'- `{t}`' for t in gaps['targets_not_verified']] or ['- none']) + ['']
    L += ['| Target | Source | Acquired | Verified | Integrated | Evidence rows | Mapped rows |', '|---|---|:-:|:-:|:-:|---:|---:|']
    mk = lambda v: 'x' if v else '.'
    L += [f"| `{r['target_id']}` | {r['source']} | {mk(r['acquired'])} | {mk(r['verified'])} | {mk(r['integrated'])} | {r['evidence_rows']:,} | {r['mapped_evidence_rows']:,} |" for r in life['targets']] + ['']
    nm = gaps.get('rows_kept_but_not_mapped') or {}
    if nm:
        L += ['## Records kept but not mapped, by source', '', 'Each of these rows is in the index with its reason; none was dropped.', '', '| Source | Rows | Largest reasons (status: reason = rows) |', '|---|---:|---|']
        for src, d in nm.items():
            top = sorted(((st, r, n) for st, v in d['by_status'].items() for r, n in v.items()), key=lambda x: -x[2])[:4]
            L.append(f"| {src} | {d['total']:,} | " + '; '.join(f'{st}: {r} = {n:,}' for st, r, n in top) + ' |')
        L.append('')
    L += ['## Modules and gaps', '', '| Module | Status | Note |', '|---|---|---|'] + [f"| {m['name']} | {m['status']} | {m.get('note', '')} |" for m in gaps['modules']] + ['']
    if change:
        L += ['## Change since the previous build', '', '```json', json.dumps(change, indent=1, sort_keys=True), '```', '']
    return '\n'.join(L)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--index', default=OUT_DEFAULT)
    ap.add_argument('--out')
    ap.add_argument('--previous')
    ap.add_argument('--markdown')
    ap.add_argument('--skip-validation', action='store_true')
    ap.add_argument('--fasta', default=FASTA)
    ap.add_argument('--assembly-report', default=REPORT)
    a = ap.parse_args(argv)
    out = a.out or os.path.join(a.index, 'reports')
    os.makedirs(out, exist_ok=True)
    t0 = time.time()
    with open(os.path.join(a.index, 'index_manifest.json')) as f:
        manifest = json.load(f)
    cov = reports.coverage(a.index)
    val = None if a.skip_validation else reports.validate(a.index, Reference(a.fasta, a.assembly_report))
    life = reports.lifecycle(a.index)
    gaps = reports.gap_report(a.index, life, cov)
    change = reports.change_log(a.previous, a.index) if a.previous else None
    for name, obj in (('coverage', cov), ('validation', val), ('lifecycle', life), ('gaps', gaps), ('change_log', change)):
        if obj is not None:
            with open(os.path.join(out, f'{name}.json'), 'w') as f:
                json.dump(obj, f, indent=1, sort_keys=True)
    if a.markdown:
        with open(a.markdown, 'w') as f:
            f.write(md(cov, val, life, gaps, change, manifest))
    print(json.dumps(dict(out=out, seconds=round(time.time() - t0, 1), validation_ok=None if val is None else val['ok'], lifecycle=life['summary'], evidence_rows=(cov.get('evidence') or {}).get('total')), indent=1))
    return 0 if (val is None or val['ok']) else 1


if __name__ == '__main__':
    sys.exit(main())
