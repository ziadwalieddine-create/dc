#!/usr/bin/env python3
"""Keep the module table of STATUS.md equal to the module registry (vindex.reports.MODULES).

    python3 variant_index/make_status.py [--write]      # without --write: exit 1 if STATUS.md is out of date

The text of STATUS.md around the table is written by hand from test and run results; only the block between the markers is generated.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from vindex import reports                                         # noqa: E402

START, END = '<!-- modules:start (generated by make_status.py) -->', '<!-- modules:end -->'


def table():
    L = ['| Module | Status | Tests | Note |', '|---|---|---|---|']
    for m in reports.MODULES:
        L.append(f"| {m['name']} | **{m['status']}** | {m.get('tests', '')} | {m.get('note', '')} |")
    return '\n'.join(L)


def render(text):
    i, j = text.index(START), text.index(END)
    return text[:i + len(START)] + '\n\n' + table() + '\n\n' + text[j:]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--write', action='store_true')
    ap.add_argument('--path', default=os.path.join(HERE, 'STATUS.md'))
    a = ap.parse_args(argv)
    with open(a.path) as f:
        text = f.read()
    new = render(text)
    if new == text:
        print('STATUS.md module table is current')
        return 0
    if a.write:
        with open(a.path, 'w') as f:
            f.write(new)
        print('STATUS.md module table rewritten')
        return 0
    print('STATUS.md module table differs from reports.MODULES; run make_status.py --write')
    return 1


if __name__ == '__main__':
    sys.exit(main())
