#!/usr/bin/env python3
"""Check requirements.json against the repository and render REQUIREMENTS.md.

    python3 variant_index/check_requirements.py            # exit 1 if a requirement names a missing file or test module, or breaks the status rules
    python3 variant_index/check_requirements.py --write    # also (re)write variant_index/REQUIREMENTS.md

requirements.json maps each clause of the project goal to the code that implements it, the test modules that exercise it and a status. This script verifies the
mapping can be followed (paths exist, test modules exist, a partial / missing status states its gap); whether the tests pass is established by running them.
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
SECTIONS = ('AUDIT', 'ACQUIRE', 'EVIDENCE', 'MATCH', 'DELIVER', 'STANDING')
NEEDS_GAP = {'partial', 'not_implemented', 'not_acquired', 'unavailable_input', 'blocked_external'}


def load(path=None):
    with open(path or os.path.join(HERE, 'requirements.json')) as f:
        return json.load(f)


def check(req, repo=REPO):
    problems, seen = [], set()
    vocab = req['status_vocabulary']
    for r in req['requirements']:
        i = r.get('id')
        if i in seen:
            problems.append(f'{i}: duplicate id')
        seen.add(i)
        if r.get('section') not in SECTIONS:
            problems.append(f'{i}: section {r.get("section")!r}')
        if r.get('status') not in vocab:
            problems.append(f'{i}: status {r.get("status")!r} is not in the vocabulary')
        if r.get('status') in NEEDS_GAP and not (r.get('gap') or '').strip():
            problems.append(f'{i}: status {r.get("status")} without a gap statement')
        if r.get('status') == 'verified' and r.get('gap'):
            problems.append(f'{i}: verified but states a gap')
        for p in r.get('code', []):
            if not os.path.exists(os.path.join(repo, p)):
                problems.append(f'{i}: code path {p} does not exist')
        for t in r.get('tests', []):
            if not os.path.exists(os.path.join(repo, 'variant_index', 'tests', t + '.py')):
                problems.append(f'{i}: test module {t} does not exist')
        if r.get('status') == 'verified' and not r.get('tests') and not r.get('code'):
            problems.append(f'{i}: verified with neither code nor tests')
    for s in SECTIONS:
        if not any(r['section'] == s for r in req['requirements']):
            problems.append(f'section {s} has no requirement')
    return problems


def render(req):
    L = ['# Requirements and verification', '',
         'Generated by `variant_index/check_requirements.py` from `requirements.json` (edit that file, not this one). Each clause of the project goal is mapped to the code that '
         'implements it, the test modules that exercise it and a status. The script verifies that every path and test module named here exists; that the tests pass is shown by running '
         '`python3 -m unittest discover` in `variant_index/tests`, and the numbers of a particular build and run are in `STATUS.md` and `BUILD_REPORT.md`.', '', '## Status vocabulary', '']
    for k, v in req['status_vocabulary'].items():
        L.append(f'- `{k}`: {v}')
    counts = {}
    for r in req['requirements']:
        counts[r['status']] = counts.get(r['status'], 0) + 1
    L += ['', '## Summary', '', ', '.join(f'{k} {v}' for k, v in sorted(counts.items(), key=lambda kv: -kv[1])) + f' (of {len(req["requirements"])} requirements).', '']
    for s in SECTIONS:
        rows = [r for r in req['requirements'] if r['section'] == s]
        L += [f'## {s.title()}', '', '| ID | Clause | Implementation | Tests | Status |', '|---|---|---|---|---|']
        for r in rows:
            code = '<br>'.join(f'`{c}`' for c in r.get('code', [])) or '-'
            tests = ', '.join(f'`{t}`' for t in r.get('tests', [])) or '-'
            L.append(f"| {r['id']} | {r['clause']} | {code} | {tests} | **{r['status']}** |")
        L.append('')
        for r in rows:
            L.append(f"**{r['id']}.** {r['how']}" + (f" *Gap:* {r['gap']}" if r.get('gap') else ''))
            L.append('')
    return '\n'.join(L).rstrip() + '\n'


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--write', action='store_true')
    a = ap.parse_args(argv)
    req = load()
    problems = check(req)
    for p in problems:
        print('PROBLEM:', p)
    if a.write:
        with open(os.path.join(HERE, 'REQUIREMENTS.md'), 'w') as f:
            f.write(render(req))
    print(f"{len(req['requirements'])} requirements, {len(problems)} problems")
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
